def line(li: str, name: str, typ: str, color: str, stations, spans=None,
         short: str = "", rush=4.0, normal=8.0, first="", last="",
         ring=False, directions=None, operator="", color2="") -> Line:
    spans = spans or {}
    default = DEFAULTS[typ]
    minutes = []
    for i in range(len(stations) - 1):
        a, b = stations[i], stations[i + 1]
        minutes.append(spans.get(f"{a}|{b}", default))
    if ring:
        minutes.append(spans.get(f"{stations[-1]}|{stations[0]}", default))
    ln = Line(
        id=li, name=name, short_name=short or name, type=typ, color=color,
        color2=color2, operator=operator, stations=list(stations), travel_minutes=minutes,
        headway_rush=rush, headway_normal=normal, first_train=first, last_train=last,
        ring=ring,
    )
    if directions is not None:
        ln.directions = [Direction(**d) for d in directions]
    return ln


